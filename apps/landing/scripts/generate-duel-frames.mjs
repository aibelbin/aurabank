/**
 * Packs the duel into a sprite sheet and writes the geometry the page imports.
 *
 * Two decisions here are about cost, not about drawing:
 *
 * **A grid, not one long strip.** The arithmetic is identical either way, but
 * 48 frames in a row is an element tens of thousands of pixels across.
 *
 * **Shrunk on the way out.** Frames are composed at full size and the finished
 * sheet is resampled down. This band sits on a page that already holds a
 * WebGL guilloché field and the story atlas in texture memory; a full-size
 * sheet here added about 54MB of decoded image to that, which is the kind of
 * pressure that makes a scroll stutter on an integrated GPU. At 0.7 it costs
 * a third of that, and the band is upscaled 1.9× on the widest screen it runs
 * on — soft at the edges, which line art on an engraved ground survives.
 *
 *   node scripts/generate-duel-frames.mjs
 */
import { writeFileSync } from "node:fs";
import { encodeGrayAlphaPng } from "./lib/gray-png.mjs";
import { blit, createSurface, resample } from "./lib/raster.mjs";
import { drawDuelFrame, DUEL_GEOMETRY } from "./lib/duel-frames.mjs";

const { FRAME_WIDTH, FRAME_HEIGHT, COLUMNS, ROWS, FRAME_COUNT } = DUEL_GEOMETRY;

/** Fourteen a second. Slower than film, and fourteen repaints rather than sixteen. */
const FPS = 14;
const SHEET_SCALE = 0.7;
const SMALL_SCALE = 0.35;

const full = createSurface(FRAME_WIDTH * COLUMNS, FRAME_HEIGHT * ROWS, 0);
for (let index = 0; index < FRAME_COUNT; index += 1) {
  const column = index % COLUMNS;
  const row = Math.floor(index / COLUMNS);
  blit(full, drawDuelFrame(index), column * FRAME_WIDTH, row * FRAME_HEIGHT);
}

function emit(path, scale) {
  const sheet =
    scale === 1
      ? full
      : resample(full, Math.round(full.width * scale), Math.round(full.height * scale));
  const png = encodeGrayAlphaPng(sheet.width, sheet.height, sheet.pixels);
  writeFileSync(path, png);
  return { sheet, png };
}

const main = emit("public/duel/duel-sheet.png", SHEET_SCALE);
const small = emit("public/duel/duel-sheet-half.png", SMALL_SCALE);

const frameWidth = Math.round(FRAME_WIDTH * SHEET_SCALE);
const frameHeight = Math.round(FRAME_HEIGHT * SHEET_SCALE);

writeFileSync(
  "lib/story/duel.ts",
  `/**
 * Geometry of public/duel/duel-sheet.png.
 *
 * Generated by scripts/generate-duel-frames.mjs — rerun it after changing the
 * artwork rather than editing these values by hand.
 */
export const DUEL_SHEET = {
  src: "/duel/duel-sheet.png",
  /** Quarter-weight sheet, for small screens. Same grid, same frame count. */
  srcSmall: "/duel/duel-sheet-half.png",
  columns: ${COLUMNS},
  rows: ${ROWS},
  frameCount: ${FRAME_COUNT},
  frameWidth: ${frameWidth},
  frameHeight: ${frameHeight},
  /** ${FPS} frames a second: fast enough to land a hit, slow enough to follow. */
  durationMs: ${Math.round((FRAME_COUNT / FPS) * 1000)},
} as const;
`,
);

const report = ({ sheet, png }, label) =>
  `${label.padEnd(8)} ${sheet.width}x${sheet.height} = ` +
  `${((sheet.width * sheet.height) / 1e6).toFixed(1)} Mpx, ` +
  `${(png.length / 1024).toFixed(0)} KB file, ` +
  `~${((sheet.width * sheet.height * 4) / 1e6).toFixed(0)} MB decoded`;

console.log(
  `${COLUMNS}x${ROWS} = ${FRAME_COUNT} frames at ${frameWidth}x${frameHeight}\n` +
    `${report(main, "sheet:")}\n${report(small, "small:")}`,
);
