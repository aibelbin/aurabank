/**
 * Packs the toon into the greyscale sprite sheet the shader samples, and writes
 * the matching geometry constants for the app to import.
 *
 *   node scripts/generate-story-frames.mjs
 */
import { writeFileSync } from "node:fs";
import { encodeGrayPng } from "./lib/gray-png.mjs";
import { blit, createSurface } from "./lib/raster.mjs";
import { drawFrame, STORY_GEOMETRY } from "./lib/story-frames.mjs";

const { FRAME_WIDTH, FRAME_HEIGHT, COLUMNS, ROWS, FRAME_COUNT } = STORY_GEOMETRY;

const atlas = createSurface(FRAME_WIDTH * COLUMNS, FRAME_HEIGHT * ROWS, 245);
for (let index = 0; index < FRAME_COUNT; index += 1) {
  const column = index % COLUMNS;
  const row = Math.floor(index / COLUMNS);
  blit(atlas, drawFrame(index), column * FRAME_WIDTH, row * FRAME_HEIGHT);
}

const png = encodeGrayPng(atlas.width, atlas.height, atlas.pixels);
writeFileSync("public/story/story-atlas.png", png);

writeFileSync(
  "lib/story/atlas.ts",
  `/**
 * Geometry of public/story/story-atlas.png.
 *
 * Generated by scripts/generate-story-frames.mjs — rerun it after changing the
 * artwork rather than editing these values by hand.
 */
export const STORY_ATLAS = {
  src: "/story/story-atlas.png",
  columns: ${COLUMNS},
  rows: ${ROWS},
  frameCount: ${FRAME_COUNT},
  frameWidth: ${FRAME_WIDTH},
  frameHeight: ${FRAME_HEIGHT},
} as const;
`,
);

console.log(
  `atlas: ${atlas.width}x${atlas.height}, ${FRAME_COUNT} frames, ${(png.length / 1024).toFixed(0)} KB`,
);
